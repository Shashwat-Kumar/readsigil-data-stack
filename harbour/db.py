"""Harbour's core ledger in Postgres: schema, seed and reconciliation queries."""
import psycopg

from . import dsn, VALUE_DATE, GL_UPI
from .data import load

SCHEMA = """
DROP TABLE IF EXISTS ledger_postings, accounts, gl_accounts, npci_raw, npci_net_settlement CASCADE;
CREATE TABLE accounts (
  account_id VARCHAR(10) PRIMARY KEY, product CHAR(2) NOT NULL, branch VARCHAR(40) NOT NULL, opened_on DATE NOT NULL);
CREATE TABLE gl_accounts (gl_code VARCHAR(12) PRIMARY KEY, name VARCHAR(40) NOT NULL);
-- The core ledger. Two legs per transaction. Since Friday's duplicate, (txn_ref, leg) is unique.
CREATE TABLE ledger_postings (
  posting_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 990001) PRIMARY KEY,
  txn_ref VARCHAR(20) NOT NULL,
  leg VARCHAR(4) NOT NULL CHECK (leg IN ('CUST', 'GL')),
  account_id VARCHAR(12) NOT NULL,
  value_date DATE NOT NULL,
  dr_cr CHAR(2) NOT NULL CHECK (dr_cr IN ('DR', 'CR')),
  amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
  channel VARCHAR(6) NOT NULL,
  narration VARCHAR(80),
  correction_ref VARCHAR(20),
  posted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_posting_leg UNIQUE (txn_ref, leg)
);
CREATE TABLE npci_raw (
  rrn VARCHAR(12) PRIMARY KEY, account_id VARCHAR(10) NOT NULL, dr_cr CHAR(2) NOT NULL, amount NUMERIC(14,2) NOT NULL,
  txn_date DATE NOT NULL, settled_at TIMESTAMP NOT NULL, response_code CHAR(2) NOT NULL);
CREATE TABLE npci_net_settlement (
  settlement_date DATE NOT NULL, inward_amount NUMERIC(16,2) NOT NULL, outward_amount NUMERIC(16,2) NOT NULL,
  net_amount NUMERIC(16,2) NOT NULL, position VARCHAR(10) NOT NULL);
"""


def connect(autocommit: bool = False) -> psycopg.Connection:
    return psycopg.connect(dsn(), autocommit=autocommit)


def reset() -> None:
    """Rebuild the ledger as it stood at 06:00 on 17 Oct, before any UPI postings for 16 Oct."""
    d = load()
    r = lambda p: f"{p / 100:.2f}"
    with connect() as conn, conn.cursor() as cur:
        cur.execute("SET TimeZone = 'Asia/Kolkata'")
        cur.execute(SCHEMA)
        cur.executemany("INSERT INTO accounts VALUES (%s,%s,%s,%s)",
                        [(a["account_id"], a["product"], a["branch"], a["opened_on"]) for a in d["accounts"]])
        cur.executemany("INSERT INTO gl_accounts VALUES (%s,%s)", list(d["gl_names"].items()))
        with cur.copy("COPY ledger_postings (posting_id, txn_ref, leg, account_id, value_date, dr_cr, amount, channel, narration, posted_at) FROM STDIN") as cp:
            for x in d["ledger_seed"]:
                cp.write_row((x["posting_id"], x["txn_ref"], x["leg"], x["account_id"], x["value_date"], x["dr_cr"], r(x["amount"]), x["channel"], x["narration"], x["posted_at"] + "+05:30"))
        with cur.copy("COPY npci_raw FROM STDIN") as cp:
            for x in d["npci_raw"]:
                cp.write_row((x["rrn"], x["account_id"], x["dr_cr"], r(x["amount"]), x["txn_date"], x["settled_at"], x["response_code"]))
        n = d["npci_net_settlement"]
        cur.execute("INSERT INTO npci_net_settlement VALUES (%s,%s,%s,%s,%s)",
                    (n["settlement_date"], r(n["inward_amount"]), r(n["outward_amount"]), r(n["net_amount"]), n["position"]))
        cur.execute("SELECT setval(pg_get_serial_sequence('ledger_postings', 'posting_id'), 990000)")


UPI_DAY = f"channel = 'UPI' AND value_date = DATE '{VALUE_DATE}'"


def upi_rows(conn) -> int:
    return conn.execute(f"SELECT COUNT(*) FROM ledger_postings WHERE {UPI_DAY}").fetchone()[0]


def upi_postings(conn) -> list:
    return conn.execute(
        f"SELECT posting_id, txn_ref, leg, account_id, dr_cr, round(amount * 100)::bigint FROM ledger_postings WHERE {UPI_DAY} ORDER BY posting_id"
    ).fetchall()


def gl_net(conn) -> int:
    """DR minus CR on the UPI settlement GL for 16 Oct, in paise (inward minus outward)."""
    v = conn.execute(
        f"SELECT COALESCE(SUM(CASE WHEN dr_cr = 'DR' THEN amount ELSE -amount END), 0) FROM ledger_postings WHERE {UPI_DAY} AND leg = 'GL' AND account_id = %s",
        (GL_UPI,),
    ).fetchone()[0]
    return int(round(v * 100))
