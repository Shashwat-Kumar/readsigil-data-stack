"""Harbour's end-of-day data for Workshop 3: NPCI raw files for 13 to 16 Oct, the ledger
those days were posted to, and the answer each night's run should produce.

The landing folder receives one CSV and one control file per business date. NPCI writes
the CSV first and the control file last, so the control file is the signal that the CSV
is complete. Two dates misbehave:
  14 Oct  the CSV is one record short of its control totals; a corrected file follows
  16 Oct  the file lands late, in two writes, after the run has started
"""
import csv
import json
import os
import random
from decimal import Decimal
from functools import lru_cache
from pathlib import Path

import psycopg

from . import GL_UPI, dsn
from .data import load

DATES = ["2026-10-13", "2026-10-14", "2026-10-15", "2026-10-16"]
FIELDS = ["rrn", "account_id", "dr_cr", "amount", "txn_date", "settled_at", "response_code"]
SHORT_DATE = "2026-10-14"
LATE_DATE = "2026-10-16"


def landing() -> Path:
    p = os.environ.get("HARBOUR_LANDING")
    path = Path(p) if p else Path(__file__).resolve().parents[1] / "landing"
    path.mkdir(parents=True, exist_ok=True)
    return path


def csv_path(d: str) -> Path:
    return landing() / f"upi_raw_{d}.csv"


def control_path(d: str) -> Path:
    return landing() / f"upi_raw_{d}.ctl"


def file_wait_seconds() -> int:
    return int(os.environ.get("HARBOUR_FILE_WAIT_SECONDS", "3600"))


def read_control(d: str) -> dict:
    """{'records': int, 'credit_total': Decimal, 'debit_total': Decimal} from the control file."""
    out = {}
    for line in control_path(d).read_text().splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return {"records": int(out["records"]), "credit_total": Decimal(out["credit_total"]), "debit_total": Decimal(out["debit_total"])}


def _generate(d: str, n: int, seed: int) -> list:
    rng = random.Random(seed)
    accts = [a["account_id"] for a in load()["accounts"]]
    jday = 289 - (16 - int(d[-2:]))
    seen, rows = set(), []
    for _ in range(n):
        sec = rng.randrange(86400)
        while True:
            rrn = f"6{jday:03d}{sec // 3600:02d}{rng.randrange(10**6):06d}"
            if rrn not in seen:
                break
        seen.add(rrn)
        amt = min(100000, max(10, round(2.718281828 ** (6.6 + 1.25 * rng.gauss(0, 1))))) * 100 + (rng.randrange(100) if rng.random() < 0.35 else 0)
        rows.append({"rrn": rrn, "account_id": rng.choice(accts), "dr_cr": "CR" if rng.random() < 0.45 else "DR", "amount": amt,
                     "txn_date": d, "settled_at": f"{d} {sec // 3600:02d}:{sec // 60 % 60:02d}:{sec % 60:02d}", "response_code": "00"})
    rows.sort(key=lambda r: r["settled_at"])
    return rows


@lru_cache(maxsize=1)
def days() -> dict:
    """{date: {'raw': [...], 'ledger_cust': [...], 'short_rrn': str|None}} with amounts in paise."""
    d = load()
    out = {}
    for date, n, seed in (("2026-10-13", 1640, 13), ("2026-10-14", 1715, 14)):
        raw = _generate(date, n, seed)
        out[date] = {"raw": raw, "ledger_cust": [dict(r) for r in raw]}
    short = out[SHORT_DATE]["raw"][1203]
    short["dr_cr"], short["amount"] = "CR", 1000000  # the ₹10,000.00 credit missing from the first 14 Oct file
    out[SHORT_DATE]["ledger_cust"] = [dict(r) for r in out[SHORT_DATE]["raw"]]
    out[SHORT_DATE]["short_rrn"] = short["rrn"]
    prior = [r for r in d["ledger_seed"] if r["channel"] == "UPI" and r["value_date"] == "2026-10-15" and r["leg"] == "CUST"]
    raw15 = sorted(({"rrn": r["txn_ref"], "account_id": r["account_id"], "dr_cr": r["dr_cr"], "amount": r["amount"], "txn_date": "2026-10-15",
                     "settled_at": r["posted_at"], "response_code": "00"} for r in prior), key=lambda r: r["settled_at"])
    out["2026-10-15"] = {"raw": raw15, "ledger_cust": [dict(r) for r in raw15]}
    raw16 = d["npci_raw"]
    b = d["ws1_breaks"]
    led16 = [dict(r) for r in raw16 if r["rrn"] != b["missing_rrn"]]
    led16 += [dict(r) for r in raw16 if r["rrn"] == b["duplicate_rrn"]]
    out["2026-10-16"] = {"raw": raw16, "ledger_cust": led16}
    return out


SCHEMA = """
DROP TABLE IF EXISTS ledger_postings, accounts, gl_accounts, npci_raw, npci_net_settlement, stg_npci_raw, recon_breaks, treasury_position CASCADE;
CREATE TABLE accounts (account_id VARCHAR(10) PRIMARY KEY, product CHAR(2) NOT NULL, branch VARCHAR(40) NOT NULL, opened_on DATE NOT NULL);
CREATE TABLE gl_accounts (gl_code VARCHAR(12) PRIMARY KEY, name VARCHAR(40) NOT NULL);
-- The core ledger as it stood on Saturday morning, before Friday's duplicate was found.
CREATE TABLE ledger_postings (
  posting_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, txn_ref VARCHAR(20) NOT NULL, leg VARCHAR(4) NOT NULL,
  account_id VARCHAR(12) NOT NULL, value_date DATE NOT NULL, dr_cr CHAR(2) NOT NULL, amount NUMERIC(14,2) NOT NULL,
  channel VARCHAR(6) NOT NULL, narration VARCHAR(80), posted_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX ON ledger_postings (value_date, channel, leg);
CREATE INDEX ON ledger_postings (txn_ref);
-- Written by the end-of-day pipeline.
CREATE TABLE stg_npci_raw (
  txn_date DATE NOT NULL, rrn VARCHAR(12) NOT NULL, account_id VARCHAR(10) NOT NULL, dr_cr CHAR(2) NOT NULL,
  amount NUMERIC(14,2) NOT NULL, settled_at TIMESTAMP NOT NULL, response_code CHAR(2) NOT NULL, loaded_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX ON stg_npci_raw (txn_date);
CREATE TABLE recon_breaks (
  business_date DATE NOT NULL, rrn VARCHAR(20) NOT NULL, account_id VARCHAR(12) NOT NULL, dr_cr CHAR(2) NOT NULL,
  amount NUMERIC(14,2) NOT NULL, break_type VARCHAR(24) NOT NULL);
-- Treasury reads this table at 09:00. It has never had a primary key.
CREATE TABLE treasury_position (
  business_date DATE NOT NULL, npci_net NUMERIC(16,2) NOT NULL, gl_net NUMERIC(16,2) NOT NULL, difference NUMERIC(16,2) NOT NULL,
  breaks INTEGER NOT NULL, published_at TIMESTAMPTZ NOT NULL DEFAULT now());
"""


def _write_csv(path: Path, rows: list) -> None:
    tmp = path.with_suffix(".part")
    with tmp.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        for r in rows:
            w.writerow({**r, "amount": f"{r['amount'] / 100:.2f}"})
    tmp.replace(path)


def _write_control(d: str, rows: list) -> None:
    cr = sum(r["amount"] for r in rows if r["dr_cr"] == "CR")
    dr = sum(r["amount"] for r in rows if r["dr_cr"] == "DR")
    control_path(d).write_text(f"file=upi_raw_{d}.csv\nrecords={len(rows)}\ncredit_total={cr / 100:.2f}\ndebit_total={dr / 100:.2f}\n")


def land(d: str, mode: str = "full") -> None:
    """full: CSV then control file. short: CSV one record short, control file for the full set.
    partial: the first 60% of the CSV only, no control file (NPCI is still writing)."""
    rows = days()[d]["raw"]
    if mode == "full":
        _write_csv(csv_path(d), rows)
        _write_control(d, rows)
    elif mode == "short":
        miss = days()[d].get("short_rrn")
        _write_csv(csv_path(d), [r for r in rows if r["rrn"] != miss])
        _write_control(d, rows)
    elif mode == "partial":
        control_path(d).unlink(missing_ok=True)
        cut = rows[: int(len(rows) * 0.6)]
        with csv_path(d).open("w", newline="") as f:  # deliberately not atomic: this is a file mid-write
            w = csv.DictWriter(f, fieldnames=FIELDS)
            w.writeheader()
            for r in cut:
                w.writerow({**r, "amount": f"{r['amount'] / 100:.2f}"})
    else:
        raise ValueError(mode)


def reset_landing() -> None:
    for p in landing().glob("upi_raw_*"):
        p.unlink()
    land("2026-10-13")
    land(SHORT_DATE, "short")
    land("2026-10-15")
    land(LATE_DATE, "partial")


def reset_db() -> None:
    d = load()
    with psycopg.connect(dsn()) as conn, conn.cursor() as cur:
        cur.execute("SET TimeZone = 'Asia/Kolkata'")
        cur.execute(SCHEMA)
        cur.executemany("INSERT INTO accounts VALUES (%s,%s,%s,%s)", [(a["account_id"], a["product"], a["branch"], a["opened_on"]) for a in d["accounts"]])
        cur.executemany("INSERT INTO gl_accounts VALUES (%s,%s)", list(d["gl_names"].items()))
        with cur.copy("COPY ledger_postings (txn_ref, leg, account_id, value_date, dr_cr, amount, channel, narration, posted_at) FROM STDIN") as cp:
            for date, day in days().items():
                for r in day["ledger_cust"]:
                    a = f"{r['amount'] / 100:.2f}"
                    t = r["settled_at"] + "+05:30"
                    cp.write_row((r["rrn"], "CUST", r["account_id"], date, r["dr_cr"], a, "UPI", "UPI", t))
                    cp.write_row((r["rrn"], "GL", GL_UPI, date, "DR" if r["dr_cr"] == "CR" else "CR", a, "UPI", "UPI", t))


def _bad_week_positions() -> list:
    """What last week's runs left in treasury_position: nothing for 13 to 15 Oct, and three
    different rows for 16 Oct (a half-read file, then two on-call reruns that appended)."""
    day = days()[LATE_DATE]
    raw, led = day["raw"], day["ledger_cust"]
    net = lambda rows: sum(r["amount"] if r["dr_cr"] == "CR" else -r["amount"] for r in rows)
    gl = net(led)
    part = net(raw[: int(len(raw) * 0.6)])
    out = []
    for npci, brk, at in ((part, 721, "2026-10-17 02:41:09+05:30"), (part + net(raw), 1802, "2026-10-17 03:05:44+05:30"), (part + 2 * net(raw), 1803, "2026-10-17 03:22:17+05:30")):
        out.append((LATE_DATE, f"{npci / 100:.2f}", f"{gl / 100:.2f}", f"{(npci - gl) / 100:.2f}", brk, at))
    return out


def reset() -> None:
    reset_db()
    with psycopg.connect(dsn()) as conn:
        conn.cursor().executemany("INSERT INTO treasury_position (business_date, npci_net, gl_net, difference, breaks, published_at) VALUES (%s,%s,%s,%s,%s,%s)", _bad_week_positions())
    reset_landing()


def expected(d: str) -> dict:
    """What a correct run publishes for date d, computed from the data, not from any DAG."""
    day = days()[d]
    raw, led = day["raw"], day["ledger_cust"]
    npci = sum(r["amount"] if r["dr_cr"] == "CR" else -r["amount"] for r in raw)
    gl = sum(r["amount"] if r["dr_cr"] == "CR" else -r["amount"] for r in led)  # GL DR-CR mirrors customer CR-DR
    raw_refs = {r["rrn"] for r in raw}
    counts = {}
    for r in led:
        counts[r["rrn"]] = counts.get(r["rrn"], 0) + 1
    breaks = sum(1 for r in raw if r["rrn"] not in counts) + sum(1 for k, n in counts.items() if n > 1) + sum(1 for k in counts if k not in raw_refs)
    return {"records": len(raw), "npci_net": npci, "gl_net": gl, "difference": npci - gl, "breaks": breaks}
